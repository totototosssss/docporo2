import assert from 'node:assert/strict';
import * as E from '../engine.js';
import {SCHOOL_MAP} from '../data.js';
import {chooseAspiration,clearAspiration,aspirationView} from '../aspiration.js';
const initial=E.newGame(5),original=structuredClone(initial);
assert.equal(aspirationView(initial),null);
assert.equal(aspirationView({...initial,aspiration:'unknown-school'}),null);
assert.equal(aspirationView({...initial,aspiration:{id:'utokyo'}}),null);
assert.throws(()=>chooseAspiration(initial,'unknown-school'));
assert.throws(()=>chooseAspiration(initial,'__proto__'));
let selected=chooseAspiration(initial,'utokyo');
assert.deepEqual(initial,original);
assert.deepEqual(selected.applications,initial.applications);
assert.deepEqual(selected.training,initial.training);
assert.equal(selected.examBudget,initial.examBudget);assert.equal(selected.cash,initial.cash);
let view=aspirationView(selected);assert.equal(view.name,SCHOOL_MAP.utokyo.name);assert.deepEqual(view.subjects.map(x=>x.id),Object.keys(E.weights(selected,SCHOOL_MAP.utokyo)));assert.equal(view.applied,false);assert.equal(view.profileBlocks,0);
selected.training.sessions[view.profile]=4;view=aspirationView(selected);assert.equal(view.profileBlocks,4);
selected.applications.push('utokyo');assert.equal(aspirationView(selected).applied,true);
const changed=chooseAspiration(selected,'kawasaki');assert.equal(changed.aspiration,'kawasaki');assert.equal(aspirationView(changed).profile,SCHOOL_MAP.kawasaki.profile);assert.deepEqual(changed.training,selected.training);
const cleared=clearAspiration(changed);assert.equal(aspirationView(cleared),null);assert.equal(changed.aspiration,'kawasaki');
const reloaded=E.migrateGame(JSON.parse(JSON.stringify(changed)));assert.equal(reloaded.aspiration,'kawasaki');
reloaded.phase='ending';const next=E.continueYear(reloaded,'enrolled');assert.equal(next.aspiration,'kawasaki');assert.equal(aspirationView(next).id,'kawasaki');assert.equal(aspirationView(next).applied,false);
const legacy=E.newGame(2);delete legacy.aspiration;const migrated=E.migrateGame(JSON.parse(JSON.stringify(legacy)));assert.equal(aspirationView(migrated),null);
assert.equal(aspirationView(chooseAspiration(initial,'twmu')).eligibility,'女子の出願資格設定が必要');
assert.equal(aspirationView(chooseAspiration(initial,'defense')).eligibility,'年齢条件外（入校時21歳以上）');
console.log('aspiration selection, school view, persistence and compatibility: passed');
